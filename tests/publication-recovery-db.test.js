async function entry(name = 'Fixture', wire = 'crypto') {
  return (await pool.query(`INSERT INTO scan_entries
    (name, description, source_url, wire, wires, prompt_variant, scan_source, scan_date, status, classification, distributable, quality_score)
    VALUES ($1, 'Fixture grant description', $2, $3, ARRAY[$3], 'A', 'manual-intake', CURRENT_DATE, 'approved', 'GRANT', true, 80) RETURNING *`,
    [name, `https://example.invalid/${name}`, wire])).rows[0];
}
async function channel(wire = 'crypto', name = 'First') {
  return (await pool.query(`INSERT INTO distribution_channels (wire, channel, name, enabled, target_id, credentials)
    VALUES ($1,'telegram',$2,true,$2,'{"bot_token":"fixture"}') RETURNING id`, [wire, name])).rows[0].id;
}

test('one failed receipt write retries persistence without resending', async (t) => {
  const e = await entry(); await channel();
  const original = db.finalizeDistributionLog;
  let writes = 0;
  t.mock.method(db, 'finalizeDistributionLog', async (...args) => {
    if (++writes === 1) throw new Error('receipt write unavailable');
    return original(...args);
  });
  await dist.distributeEntry(e.id, e.wire);
  await dist.retryDistribution(e.id, e.wire);
  assert.equal(sends, 1);
  const logs = await db.getDistributionLogs(e.id);
  assert.equal(logs.length, 1); assert.equal(logs[0].status, 'success'); assert.equal(logs[0].externalId, '1');
});

test('persistent receipt failure blocks resend and keeps the returned message ID for review', async (t) => {
  const e = await entry(); await channel();
  t.mock.method(db, 'finalizeDistributionLog', async () => { throw new Error('receipt unavailable'); });
  await assert.rejects(dist.distributeEntry(e.id, e.wire), /receipt unavailable/);
  await dist.retryDistribution(e.id, e.wire);
  assert.equal(sends, 1);
  const review = await queue.listPublicationReview();
  assert.equal(review.length, 1); assert.equal(review[0].external_id, '1');
  await queue.resolvePublication(review[0].id, true, undefined, 'user:test');
  await queue.drainPublicationQueue();
  assert.equal(sends, 1);
  assert.equal((await db.getDistributionLogs(e.id))[0].status, 'success');
});

test('partial managed delivery retries only the missing destination and stays in backlog', async () => {
  const e = await entry(); const a = await channel(); const b = await channel('crypto', 'Second');
  await db.logDistribution({ entryId: e.id, channel: 'telegram', channelId: a, wire: e.wire, status: 'success', externalId: 'old' });
  await db.logDistribution({ entryId: e.id, channel: 'telegram', channelId: b, wire: e.wire, status: 'failed' });
  assert.equal((await db.getUndistributedEntries(e.wire)).length, 1);
  await dist.retryDistribution(e.id, e.wire);
  assert.equal(sends, 1);
  assert.equal((await db.getUndistributedEntries(e.wire)).length, 0);
});

