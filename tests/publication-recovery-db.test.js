test('stale claims require recorded human confirmation before a retry', async () => {
  const e = await entry(); const ch = await channel();
  const claim = await db.claimDistributionLog({ entryId: e.id, channel: 'telegram', channelId: ch, wire: e.wire });
  await pool.query("UPDATE distribution_logs SET lease_expires_at = NOW() - INTERVAL '7 days' WHERE id = $1", [claim.id]);
  assert.equal((await queue.listPublicationReview()).length, 1);
  await dist.retryDistribution(e.id, e.wire); assert.equal(sends, 0);
  await queue.resolvePublication(claim.id, false, undefined, 'user:test');
  await queue.drainPublicationQueue(); assert.equal(sends, 1);
  const audit = (await pool.query('SELECT resolved_by, resolved_at FROM distribution_logs WHERE id = $1', [claim.id])).rows[0];
  assert.equal(audit.resolved_by, 'user:test'); assert.ok(audit.resolved_at);
});

test('queued approvals survive worker restart and quiet entries never publish', async () => {
  const e = await entry(); await channel();
  await pool.query('INSERT INTO publication_queue (entry_id) VALUES ($1)', [e.id]);
  await queue.drainPublicationQueue(); assert.equal(sends, 1);
  await pool.query("UPDATE publication_queue SET status = 'running', lease_expires_at = NOW() - INTERVAL '1 hour'");
  await queue.drainPublicationQueue(); assert.equal(sends, 1);
  const quiet = await entry('Quiet');
  await pool.query('UPDATE scan_entries SET distributable = false WHERE id = $1', [quiet.id]);
  await pool.query('INSERT INTO publication_queue (entry_id) VALUES ($1)', [quiet.id]);
  await queue.drainPublicationQueue(); assert.equal(sends, 1);
});

test('approval and queue insertion commit together; quiet approvals create no publication job', async (t) => {
  const actions = require('../src/services/entry-actions');
  t.mock.method(queue, 'drainPublicationQueue', async () => {});
  t.mock.method(db, 'insertApprovedSummary', async () => null);
  const a = await entry('Atomic'); const q = await entry('QuietApproval'); const blocked = await entry('Blocked');
  await pool.query("UPDATE scan_entries SET status = 'queued', org_id = 1, enriched_summary = repeat('summary ',20)");
  await actions.singleEntryAction(a.id, 'approve', { actor: 'user:test' });
  await actions.singleEntryAction(q.id, 'approve', { quiet: true, actor: 'user:test' });
  assert.deepEqual((await pool.query('SELECT entry_id FROM publication_queue')).rows.map(r => r.entry_id), [a.id]);
  await pool.query(`CREATE FUNCTION reject_queue_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'queue write rejected'; END $$`);
  await pool.query('CREATE TRIGGER reject_queue BEFORE INSERT ON publication_queue FOR EACH ROW EXECUTE FUNCTION reject_queue_insert()');
  try {
    await assert.rejects(actions.singleEntryAction(blocked.id, 'approve'), /queue write rejected/);
    assert.equal((await pool.query('SELECT status FROM scan_entries WHERE id=$1', [blocked.id])).rows[0].status, 'queued');
  } finally {
    await pool.query('DROP TRIGGER reject_queue ON publication_queue');
    await pool.query('DROP FUNCTION reject_queue_insert()');
    await new Promise(resolve => setImmediate(resolve));
  }
});

