// Curator acknowledge closes a failed distribution log and does not send.
const crypto = require('node:crypto');

function sha(token) {
  return crypto.createHash('sha256').update(token).digest('hex');
}

const TOKEN = 'hedwig-acknowledge-test-token';
const READ = 'reader-acknowledge-test-token';
process.env.DEV_MODE = 'false';
process.env.DATABASE_URL = process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/wireops_test';
process.env.DB_SSL_REJECT_UNAUTHORIZED = 'false';
process.env.NOTIFICATION_EMAIL = 'ops@example.com';
process.env.PRIVY_APP_ID = 'test-app-id';
process.env.PRIVY_APP_SECRET = 'test-app-secret';
process.env.NODE_ENV = 'test';
process.env.INTERNAL_API_KEY = 'internal-acknowledge-test-key';
process.env.WIRE_ROOM_CURATOR_KEYS = JSON.stringify([
  {
    id: 'hedwig', name: 'Hedwig', sha256: sha(TOKEN),
    scopes: ['read_queue', 'decide', 'propose'],
    expires_at: '2099-01-01T00:00:00.000Z', revoked: false,
  },
  {
    id: 'reader', name: 'Reader', sha256: sha(READ),
    scopes: ['read_queue'],
    expires_at: '2099-01-01T00:00:00.000Z', revoked: false,
  },
]);

const schema = `ack_dist_${process.pid}_${Date.now()}`;
process.env.PGOPTIONS = `-c search_path=${schema}`;

require('ts-node/register/transpile-only');
const test = require('node:test');
const assert = require('node:assert/strict');
const { Pool } = require('pg');

const admin = new Pool({ connectionString: process.env.DATABASE_URL, options: '' });
let server;
let base;
let db;
let pool;
let idemSeq = 0;

function idem() {
  idemSeq += 1;
  return `ack-key-${idemSeq}-abcd`;
}

async function post(path, body, token = TOKEN, key = idem()) {
  return fetch(`${base}${path}`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
      'Idempotency-Key': key,
    },
    body: JSON.stringify(body),
  });
}

test.before(async () => {
  await admin.query(`CREATE SCHEMA ${schema}`);
  db = require('../src/db');
  pool = db.getPool();
  await pool.query('CREATE TABLE scan_entries (LIKE public.scan_entries INCLUDING ALL)');
  await pool.query('ALTER TABLE scan_entries ALTER COLUMN id DROP DEFAULT');
  await pool.query('ALTER TABLE scan_entries ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
  await db.ensureDistributionTables();
  await db.ensureAppStateTable();
  const { app } = require('../src/server');
  server = await new Promise(resolve => {
    const listening = app.listen(0, '127.0.0.1', () => resolve(listening));
  });
  base = `http://127.0.0.1:${server.address().port}`;
});

test.after(async () => {
  if (server) await new Promise(resolve => server.close(resolve));
  await db.closePool();
  await admin.query(`DROP SCHEMA ${schema} CASCADE`);
  await admin.end();
});

async function entry() {
  return (await pool.query(`INSERT INTO scan_entries
    (name, description, source_url, wire, wires, prompt_variant, scan_source, scan_date, status, classification, distributable)
    VALUES ('Ack', 'A grant', 'https://example.invalid/ack', 'crypto', ARRAY['crypto'], 'A', 'manual-intake', CURRENT_DATE, 'approved', 'GRANT', true)
    RETURNING id`)).rows[0].id;
}

async function log(entryId, status, externalId = null) {
  return (await pool.query(
    `INSERT INTO distribution_logs (entry_id, channel, wire, status, error_message, external_id)
     VALUES ($1, 'telegram', 'crypto', $2, 'Telegram API call failed', $3) RETURNING id`,
    [entryId, status, externalId],
  )).rows[0].id;
}

test('acknowledge requires confirm and a reason and writes nothing otherwise', async () => {
  const entryId = await entry();
  const id = await log(entryId, 'failed');
  const missingConfirm = await post(`/api/distribution/logs/${id}/acknowledge`, { reason: 'Because' });
  assert.equal(missingConfirm.status, 400);
  assert.equal((await missingConfirm.json()).error, 'confirm_required');
  const missingReason = await post(`/api/distribution/logs/${id}/acknowledge`, { confirm: true, reason: '   ' });
  assert.equal(missingReason.status, 400);
  assert.match((await missingReason.json()).error, /reason is required/);
  const stored = (await pool.query('SELECT status FROM distribution_logs WHERE id = $1', [id])).rows[0];
  assert.equal(stored.status, 'failed');
});

test('acknowledge closes a failed log and replays, and refuses success or pending', async () => {
  const entryId = await entry();
  const failed = await log(entryId, 'failed', 'keep');
  const key = idem();
  const ok = await post(`/api/distribution/logs/${failed}/acknowledge`, {
    confirm: true,
    reason: 'Telegram rejected the chat',
  }, TOKEN, key);
  assert.equal(ok.status, 200);
  const body = await ok.json();
  assert.equal(body.status, 'acknowledged');
  assert.equal(body.externalId, 'keep');
  assert.equal(body.enqueued, false);
  assert.equal(body.sent, false);
  assert.equal(body.delivered, false);
  assert.equal(body.acknowledgedBy, 'agent:hedwig');
  const replay = await post(`/api/distribution/logs/${failed}/acknowledge`, {
    confirm: true,
    reason: 'Telegram rejected the chat',
  }, TOKEN, key);
  assert.equal(replay.status, 200);
  assert.equal(replay.headers.get('idempotent-replayed'), 'true');
  const differentBody = await post(`/api/distribution/logs/${failed}/acknowledge`, {
    confirm: true,
    reason: 'A different reason on the same key',
  }, TOKEN, key);
  assert.equal(differentBody.status, 409);
  assert.match((await differentBody.json()).error, /different request body/);
  const again = await post(`/api/distribution/logs/${failed}/acknowledge`, {
    confirm: true,
    reason: 'A different reason',
  });
  assert.equal(again.status, 409);
  const queueCount = (await pool.query('SELECT count(*) FROM publication_queue WHERE entry_id = $1', [entryId])).rows[0].count;
  assert.equal(queueCount, '0');
  const stored = (await pool.query('SELECT status, external_id FROM distribution_logs WHERE id = $1', [failed])).rows[0];
  assert.equal(stored.status, 'acknowledged');
  assert.equal(stored.external_id, 'keep');

  const success = await log(entryId, 'success', '99');
  const sent = await post(`/api/distribution/logs/${success}/acknowledge`, { confirm: true, reason: 'no' });
  assert.equal(sent.status, 409);
  assert.match((await sent.json()).error, /status is success/);
  const pending = await log(await entry(), 'pending');
  const waiting = await post(`/api/distribution/logs/${pending}/acknowledge`, { confirm: true, reason: 'no' });
  assert.equal(waiting.status, 409);
  assert.match((await waiting.json()).error, /status is pending/);
  const reader = await post(`/api/distribution/logs/${pending}/acknowledge`, { confirm: true, reason: 'no' }, READ);
  assert.equal(reader.status, 403);
});
