/** Approve-time enqueue, then one worker pass with pacing off. */
async function publishOnce(e) {
  await pool.query(`INSERT INTO publication_queue (entry_id) VALUES ($1)`, [e.id]);
  await queue.drainPublicationQueue();
}

async function queueRow(id) {
  return (await pool.query('SELECT status, error_message FROM publication_queue WHERE entry_id = $1', [id])).rows[0] || null;
}

async function logs(id) {
  return (await pool.query('SELECT id, status, needs_review, external_id, error_message, resolved_by FROM distribution_logs WHERE entry_id = $1 ORDER BY id', [id])).rows;
}

/** A send whose outcome Telegram never confirmed: the stuck state from production. */
async function stuckEntry(name = 'Flap Fixture Fund Season 4') {
  const e = await entry(name);
  await channel();
  telegram = async () => null;
  await publishOnce(e);
  telegram = async () => ({ messageId: 100 + sends });
  return e;
}

function postJson(urlPath, body, { key = TOKEN, idempotency } = {}) {
  return fetch(`${base}${urlPath}`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      ...(key ? { Authorization: `Bearer ${key}` } : {}),
      ...(idempotency ? { 'Idempotency-Key': idempotency } : {}),
    },
    body: JSON.stringify(body ?? {}),
  });
}

function idem() {
  idemSeq += 1;
  return `release-key-${idemSeq}-abcd`;
}

test('message ids and t.me links parse; only a 4xx ok:false body is a definite rejection', () => {
  assert.equal(release.parseTelegramMessageId('4512'), '4512');
  assert.equal(release.parseTelegramMessageId(' https://t.me/grantwire/4512 '), '4512');
  assert.equal(release.parseTelegramMessageId('https://t.me/c/1234567890/77?single'), '77');
  assert.equal(release.parseTelegramMessageId('https://evil.example/t.me/x/1'), null);
  assert.equal(release.parseTelegramMessageId('abc'), null);
  assert.equal(release.telegramMessageLink('@grantwire', '9'), 'https://t.me/grantwire/9');
  assert.equal(release.telegramMessageLink('-1001234567890', '9'), 'https://t.me/c/1234567890/9');
  assert.equal(release.telegramMessageLink('12345', '9'), null);

  const { isDefiniteTelegramRejection } = require('../src/services/telegram-channel');
  assert.equal(isDefiniteTelegramRejection({ ok: false, error_code: 400, description: "Bad Request: can't parse entities" }), true);
  assert.equal(isDefiniteTelegramRejection({ ok: false, error_code: 429, description: 'Too Many Requests' }), true);
  assert.equal(isDefiniteTelegramRejection({ ok: false, error_code: 502, description: 'Bad Gateway' }), false);
  assert.equal(isDefiniteTelegramRejection({ ok: false }), false);
  assert.equal(isDefiniteTelegramRejection(null), false);
});

test('a definite Telegram rejection records a failed send, so retry needs no verification and posts once', async () => {
  const e = await entry();
  await channel();
  telegram = async (_token, _chat, _text, opts) => {
    opts?.onRejected?.("400: Bad Request: can't parse entities");
    return null;
  };
  await publishOnce(e);
  let rows = await logs(e.id);
  assert.equal(rows.length, 1);
  assert.equal(rows[0].status, 'failed');
  assert.equal(rows[0].needs_review, false);
  assert.match(rows[0].error_message, /Telegram rejected the send \(400/);
  const stuck = await queueRow(e.id);
  assert.equal(stuck.status, 'review');
  assert.match(stuck.error_message, /nothing was posted/);
  assert.deepEqual((await queue.listPublicationReview()).length, 0);

  telegram = async () => ({ messageId: 555 });
  await queue.retryQueuedPublication(e.id, { actor: 'user:ops' });
  await queue.drainPublicationQueue();
  rows = await logs(e.id);
  assert.deepEqual(rows.map(row => row.status), ['failed', 'success']);
  assert.equal(rows[1].external_id, '555');
  assert.equal((await queueRow(e.id)).status, 'done');
  assert.equal(sends, 2);
});

test('an unknown outcome stays unverified, enqueue points at release, and release refuses without a verdict', async () => {
  const e = await stuckEntry();
  const [log] = await logs(e.id);
  assert.equal(log.status, 'pending');
  assert.equal(log.needs_review, true);
  assert.deepEqual(await queueRow(e.id), { status: 'review', error_message: queue.VERIFY_BEFORE_RETRY });

  await enablePace();
  await assert.rejects(queue.enqueuePacedPublication(e.id, { actor: 'user:ops', reason: 'retry' }), (error) => {
    assert.match(error.message, /already has a review publication/);
    assert.match(error.message, new RegExp(`/api/distribution/queue/${e.id}/release`));
    return true;
  });

  const verification = await release.getPublicationVerification(e.id);
  assert.equal(verification.state, 'needs_verification');
  assert.equal(verification.deliveries.length, 1);
  assert.equal(verification.deliveries[0].verdict, 'unverified');
  assert.equal(verification.deliveries[0].postText, 'fixture post');
  assert.equal(verification.deliveries[0].targetId, '@wirefixture');
  assert.match(verification.nextStep, /deliveries/);

  await assert.rejects(
    release.releaseStuckPublication(e.id, { decisions: [], actor: 'user:ops', reason: 'checked' }),
    (error) => error.statusCode === 409 && /verification_required/.test(error.message) && error.details.unverified[0].logId === log.id,
  );
  assert.equal((await queueRow(e.id)).status, 'review');
});

test('verified not delivered releases for retry without sending; repeat is a no-op; enqueue then posts exactly once', async () => {
  const e = await stuckEntry();
  const [log] = await logs(e.id);
  assert.equal(sends, 1);

  const preview = await release.releaseStuckPublication(e.id, {
    decisions: [{ logId: log.id, delivered: false }], actor: 'user:ops', reason: 'Checked the channel', dryRun: true,
  });
  assert.equal(preview.dryRun, true);
  assert.equal(preview.outcome, 'released_for_retry');
  assert.equal((await queueRow(e.id)).status, 'review');
  assert.equal((await logs(e.id))[0].status, 'pending');

  const released = await release.releaseStuckPublication(e.id, {
    decisions: [{ logId: log.id, delivered: false }], actor: 'user:ops', reason: 'Checked the channel; no post',
  });
  assert.equal(released.changed, true);
  assert.equal(released.outcome, 'released_for_retry');
  assert.deepEqual(released.queueStatus, { before: 'review', after: 'done' });
  assert.equal(released.sent, false);
  assert.equal(released.enqueued, false);
  const after = await logs(e.id);
  assert.equal(after[0].status, 'failed');
  assert.equal(after[0].resolved_by, 'user:ops');
  assert.match((await queueRow(e.id)).error_message, /^Released by user:ops/);
  const stamp = (await pool.query('SELECT metadata FROM scan_entries WHERE id = $1', [e.id])).rows[0].metadata;
  assert.equal(stamp.publication_releases.length, 1);
  assert.equal(stamp.publication_releases[0].queue_error_before, queue.VERIFY_BEFORE_RETRY);

  await queue.drainPublicationQueue();
  assert.equal(sends, 1, 'release alone never sends');

  const again = await release.releaseStuckPublication(e.id, {
    decisions: [{ logId: log.id, delivered: false }], actor: 'user:ops', reason: 'Checked the channel; no post',
  });
  assert.equal(again.changed, false);
  assert.equal(again.outcome, 'released_for_retry');
  await assert.rejects(
    release.releaseStuckPublication(e.id, { decisions: [{ logId: log.id, delivered: true, externalId: '9' }], actor: 'user:ops', reason: 'x' }),
    (error) => error.statusCode === 409 && /already failed/.test(error.message),
  );

  await enablePace();
  await queue.enqueuePacedPublication(e.id, { actor: 'user:ops', reason: 'Retry after verified non-delivery' });
  await pool.query(`UPDATE publication_queue SET available_at = NOW() - INTERVAL '1 minute' WHERE entry_id = $1`, [e.id]);
  await queue.drainPublicationQueue();
  await queue.drainPublicationQueue();
  const final = await logs(e.id);
  assert.deepEqual(final.map(row => row.status), ['failed', 'success']);
  assert.equal(sends, 2);
  assert.equal((await queueRow(e.id)).status, 'done');
});

test('verified delivered with a t.me link marks it sent, and nothing can post it again', async () => {
  const e = await stuckEntry();
  const [log] = await logs(e.id);
  await assert.rejects(
    release.releaseStuckPublication(e.id, { decisions: [{ logId: log.id, delivered: true }], actor: 'user:ops', reason: 'Seen' }),
    (error) => error.statusCode === 400 && /message id is required/.test(error.message),
  );
  const result = await release.releaseStuckPublication(e.id, {
    decisions: [{ logId: log.id, delivered: true, externalId: 'https://t.me/wirefixture/4512' }],
    actor: 'user:ops', reason: 'Post is in the channel',
  });
  assert.equal(result.outcome, 'sent');
  const [row] = await logs(e.id);
  assert.equal(row.status, 'success');
  assert.equal(row.external_id, '4512');
  assert.equal((await queueRow(e.id)).status, 'done');
  const verification = await release.getPublicationVerification(e.id);
  assert.equal(verification.deliveries[0].messageLink, 'https://t.me/wirefixture/4512');

  await enablePace();
  await assert.rejects(queue.enqueuePacedPublication(e.id, { actor: 'user:ops', reason: 'x' }), /successful Telegram send/);
  await require('../src/services/distribution').retryDistribution(e.id, e.wire);
  await queue.drainPublicationQueue();
  assert.equal(sends, 1);
});

test('release refuses while a send holds a live claim, and for withheld or scheduled rows', async () => {
  const e = await entry('Live claim');
  const channelId = await channel();
  await pool.query(`INSERT INTO publication_queue (entry_id, status) VALUES ($1, 'review')`, [e.id]);
  const claim = await db.claimDistributionLog({ entryId: e.id, channel: 'telegram', wire: 'crypto', channelId, postText: 'x' });
  await assert.rejects(
    release.releaseStuckPublication(e.id, { decisions: [{ logId: claim.id, delivered: false }], actor: 'user:ops', reason: 'x' }),
    (error) => error.statusCode === 409 && /in progress/.test(error.message),
  );
  assert.equal((await release.getPublicationVerification(e.id)).state, 'sending');

  const held = await entry('Held');
  await pool.query(`INSERT INTO publication_queue (entry_id, status) VALUES ($1, 'withheld')`, [held.id]);
  await assert.rejects(release.releaseStuckPublication(held.id, { decisions: [], actor: 'u', reason: 'x' }), /withheld/);
  const scheduled = await entry('Scheduled');
  await pool.query(`INSERT INTO publication_queue (entry_id, status, available_at) VALUES ($1, 'queued', NOW() + INTERVAL '1 hour')`, [scheduled.id]);
  await assert.rejects(release.releaseStuckPublication(scheduled.id, { decisions: [], actor: 'u', reason: 'x' }), /scheduled, not stuck/);
  await assert.rejects(release.releaseStuckPublication(999999, { decisions: [], actor: 'u', reason: 'x' }), (error) => error.statusCode === 404);
  const other = await stuckEntry('Other');
  const review = await entry('Review without logs');
  await pool.query(`INSERT INTO publication_queue (entry_id, status) VALUES ($1, 'review')`, [review.id]);
  await assert.rejects(
    release.releaseStuckPublication(review.id, { decisions: [{ logId: (await logs(other.id))[0].id, delivered: false }], actor: 'u', reason: 'x' }),
    (error) => error.statusCode === 404 && /does not belong/.test(error.message),
  );
});

test('a review row with nothing unverified (the "No new delivery confirmed" loop) releases without deliveries', async () => {
  const e = await entry('Neon Fixture', 'oss');
  // No enabled OSS destination: the worker cannot send and cannot finish.
  await publishOnce(e);
  assert.deepEqual(await queueRow(e.id), { status: 'review', error_message: 'No new delivery confirmed; check destinations and receipts' });
  await queue.retryQueuedPublication(e.id);
  await queue.drainPublicationQueue();
  assert.equal((await queueRow(e.id)).status, 'review', 'retry alone loops back to review');

  const verification = await release.getPublicationVerification(e.id);
  assert.equal(verification.state, 'releasable');
  const result = await release.releaseStuckPublication(e.id, { decisions: [], actor: 'user:ops', reason: 'Destination was missing' });
  assert.equal(result.outcome, 'no_open_destination');
  assert.equal((await queueRow(e.id)).status, 'done');
  assert.equal(sends, 0);
});

test('HTTP: verification is a read_queue GET; release needs confirm, a reason, decide scope, and replays by Idempotency-Key', async () => {
  const e = await stuckEntry();
  const [log] = await logs(e.id);

  const read = await fetch(`${base}/api/distribution/queue/${e.id}/verification`, { headers: { Authorization: `Bearer ${READ}` } });
  assert.equal(read.status, 200);
  const body = await read.json();
  assert.equal(body.state, 'needs_verification');
  assert.equal(body.deliveries[0].logId, log.id);

  const { curatorConfirmRequired } = require('../src/services/curator-confirm');
  assert.equal(curatorConfirmRequired('POST', `/api/distribution/queue/${e.id}/release`, {}), true);

  let res = await postJson(`/api/distribution/queue/${e.id}/release`, { reason: 'x' }, { idempotency: idem() });
  assert.equal(res.status, 400);
  assert.equal((await res.json()).error, 'confirm_required');
  res = await postJson(`/api/distribution/queue/${e.id}/release`, { confirm: true }, { idempotency: idem() });
  assert.equal(res.status, 400);
  res = await postJson(`/api/distribution/queue/${e.id}/release`, { confirm: true, reason: 'x' }, { key: READ, idempotency: idem() });
  assert.equal(res.status, 403);
  res = await postJson(`/api/distribution/queue/${e.id}/release`, { confirm: true, reason: 'x', deliveries: [{ logId: log.id }] }, { idempotency: idem() });
  assert.equal(res.status, 400);
  res = await postJson(`/api/distribution/queue/${e.id}/release`, { confirm: true, reason: 'x' }, { idempotency: idem() });
  assert.equal(res.status, 409);
  assert.equal((await res.json()).details.unverified[0].logId, log.id);

  const key = idem();
  const payload = { confirm: true, reason: 'Checked the channel; no post', deliveries: [{ logId: log.id, delivered: false }] };
  res = await postJson(`/api/distribution/queue/${e.id}/release`, payload, { idempotency: key });
  assert.equal(res.status, 200);
  const first = await res.json();
  assert.equal(first.outcome, 'released_for_retry');
  assert.equal(first.sent, false);
  res = await postJson(`/api/distribution/queue/${e.id}/release`, payload, { idempotency: key });
  assert.equal(res.status, 200);
  assert.equal(res.headers.get('idempotent-replayed'), 'true');
  assert.deepEqual(await res.json(), first);
  assert.equal(sends, 1);
});
