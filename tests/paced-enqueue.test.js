test('enqueue refuses an entry that is not approved or already on the queue', async () => {
  await channel('crypto', 'crypto-chat');
  await enablePace();
  const queued = await entry('Still queued');
  const notApproved = await postJson(`/api/distribution/queue/${queued.id}/enqueue`, {
    confirm: true,
    reason: 'Book a slot.',
  });
  assert.equal(notApproved.status, 409);
  assert.match((await notApproved.json()).error, /not approved/);
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM publication_queue')).rows[0].n, 0);

  for (const status of ['withheld', 'queued', 'running', 'review']) {
    const row = await approvedQuiet(status);
    const before = await snap(row.id);
    await pool.query(
      `INSERT INTO publication_queue (entry_id, status, available_at) VALUES ($1, $2, NOW() + INTERVAL '1 hour')`,
      [row.id, status],
    );
    const res = await postJson(`/api/distribution/queue/${row.id}/enqueue`, {
      confirm: true,
      reason: 'Book a slot.',
    });
    assert.equal(res.status, 409, status);
    const body = await res.json();
    if (status === 'withheld') assert.match(body.error, /withheld/);
    else assert.match(body.error, new RegExp(status));
    const after = await snap(row.id);
    assert.equal(after.entry.distributable, before.entry.distributable);
    assert.equal(after.entry.status, 'approved');
    assert.equal(after.queue.status, status);
    assert.equal(after.entry.metadata.enqueued, undefined);
  }
});

