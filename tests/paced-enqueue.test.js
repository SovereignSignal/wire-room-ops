async function approvedQuiet(name, opts = {}) {
  const row = await entry(name, opts.wire || 'crypto', opts.wires || [opts.wire || 'crypto']);
  await pool.query(
    `UPDATE scan_entries
     SET status = 'approved', distributable = false, actioned_by = $2,
         decision_at = COALESCE($3::timestamptz, NOW()),
         metadata = $4::jsonb
     WHERE id = $1`,
    [row.id, opts.actor || 'agent:hedwig', opts.decisionAt || null, JSON.stringify(opts.metadata || { keeper: true })],
  );
  return row;
}

async function snap(id) {
  const entryRow = (await pool.query(
    'SELECT status, distributable, actioned_by, metadata FROM scan_entries WHERE id = $1',
    [id],
  )).rows[0];
  const queue = (await pool.query(
    'SELECT status, available_at, error_message FROM publication_queue WHERE entry_id = $1',
    [id],
  )).rows[0] || null;
  return { entry: entryRow, queue };
}

function minutesApart(later, earlier) {
  return (new Date(later).getTime() - new Date(earlier).getTime()) / 60000;
}

function minutesOf(date, timeZone) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-US', {
    timeZone, hourCycle: 'h23', hour: '2-digit', minute: '2-digit',
  }).formatToParts(date).filter(part => part.type !== 'literal').map(part => [part.type, part.value]));
  let hour = Number(parts.hour);
  if (hour === 24) hour = 0;
  return hour * 60 + Number(parts.minute);
}

function hhmm(total) {
  const minute = ((total % 1440) + 1440) % 1440;
  return `${String(Math.floor(minute / 60)).padStart(2, '0')}:${String(minute % 60).padStart(2, '0')}`;
}

function quietCovering(date) {
  const minute = minutesOf(date, 'America/Los_Angeles');
  return { start: hhmm(minute - 30), end: hhmm(minute + 90) };
}

