test('enqueue books the next paced slot, flips distributable, and does not send', async (t) => {
  const distribution = require('../src/services/distribution');
  const queue = require('../src/services/publication-queue');
  let distributed = 0;
  let drained = 0;
  t.mock.method(distribution, 'distributeEntry', async () => {
    distributed += 1;
    return { totalEntries: 0, failed: 0, skipped: 0 };
  });
  t.mock.method(queue, 'drainPublicationQueue', async () => { drained += 1; });

  await channel('crypto', 'crypto-chat');
  await enablePace();
  const held = await approvedQuiet('Held back');
  await pool.query(
    `INSERT INTO publication_queue (entry_id, status, available_at)
     VALUES ($1, 'queued', NOW() + INTERVAL '40 minutes')`,
    [(await approvedQuiet('Already booked')).id],
  );
  const before = await snap(held.id);
  const res = await postJson(`/api/distribution/queue/${held.id}/enqueue`, {
    confirm: true,
    reason: 'Still open.',
    sources: ['https://example.org/program'],
  });
  assert.equal(res.status, 200);
  const body = await res.json();
  assert.equal(body.entryId, held.id);
  assert.equal(body.note, null);
  const booked = (await pool.query(
    'SELECT available_at FROM publication_queue WHERE entry_id = $1 AND status = $2',
    [(await pool.query("SELECT entry_id FROM publication_queue WHERE status = 'queued' AND entry_id <> $1", [held.id])).rows[0].entry_id, 'queued'],
  )).rows[0];
  const slot = (await pool.query('SELECT status, available_at FROM publication_queue WHERE entry_id = $1', [held.id])).rows[0];
  assert.equal(slot.status, 'queued');
  assert.ok(Math.abs(minutesApart(slot.available_at, booked.available_at) - 20) < 0.5);
  assert.equal(body.availableAt, new Date(slot.available_at).toISOString());

  const after = await snap(held.id);
  assert.equal(after.entry.distributable, true);
  assert.equal(after.entry.status, 'approved');
  assert.equal(after.entry.actioned_by, before.entry.actioned_by);
  assert.equal(after.entry.metadata.keeper, true);
  assert.equal(after.entry.metadata.enqueued.by, 'agent:hedwig');
  assert.equal(after.entry.metadata.enqueued.reason, 'Still open.');
  assert.deepEqual(after.entry.metadata.enqueued.sources, ['https://example.org/program']);
  for (let i = 0; i < 20; i++) await new Promise(resolve => setImmediate(resolve));
  assert.equal(distributed, 0);
  assert.equal(drained, 0);
  assert.equal(sends, 0);
});

