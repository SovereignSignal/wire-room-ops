// Open calls past their deadline are closed (not deleted) before grants.watch reads them.
require('ts-node/register/transpile-only');
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const expiry = require('../src/services/open-call-expiry');

function closes(date, text) {
  return expiry.deadlineCloseInstant(date, text)?.closesAt.toISOString();
}

test('a deadline with no time or zone closes at the end of that day Anywhere on Earth', () => {
  assert.equal(closes('2026-10-20', null), '2026-10-21T12:00:00.000Z');
  assert.equal(closes('2026-10-20', 'October 20, 2026'), '2026-10-21T12:00:00.000Z');
  assert.equal(expiry.deadlineCloseInstant('2026-10-20', 'Oct 20').basis, 'end_of_day');
});

test('a stated time and zone is honoured, including daylight saving and fixed offsets', () => {
  assert.equal(closes('2026-10-20', 'October 20, 2026 11:59 PM ET'), '2026-10-21T03:59:00.000Z');
  assert.equal(closes('2026-12-01', 'Dec 1, 2026 11:59 PM ET'), '2026-12-02T04:59:00.000Z');
  assert.equal(closes('2026-10-20', '2026-10-20 17:00 UTC'), '2026-10-20T17:00:00.000Z');
  assert.equal(closes('2026-10-20', 'Oct 20, 5pm PT'), '2026-10-21T00:00:00.000Z');
  assert.equal(closes('2026-10-20', 'Oct 20 23:59 AoE'), '2026-10-21T11:59:00.000Z');
  assert.equal(closes('2026-12-01', '1 Dec 2026, 12:00 CET'), '2026-12-01T11:00:00.000Z');
  assert.equal(closes('2026-10-20', 'Oct 20, 12 p.m. GMT+2'), '2026-10-20T10:00:00.000Z');
  assert.equal(closes('2026-10-20', 'Oct 20 noon UTC'), '2026-10-20T12:00:00.000Z');
  // A zone with no time closes at the end of the day there.
  assert.equal(closes('2026-10-20', 'Oct 20 (UTC+2)'), '2026-10-20T22:00:00.000Z');
  assert.equal(closes('2026-10-20', 'October 20 PT'), '2026-10-21T07:00:00.000Z');
  assert.equal(expiry.deadlineCloseInstant('2026-10-20', '5pm PT').basis, 'stated_time');
});

test('words that only look like zones do not count, and a bad date is ignored', () => {
  assert.equal(closes('2026-10-20', 'Interest forms due; ETH builders'), '2026-10-21T12:00:00.000Z');
  assert.equal(expiry.deadlineCloseInstant('rolling', 'Rolling'), null);
  assert.equal(expiry.deadlineCloseInstant('', null), null);
});

test('the grace period runs after the close, and its setting is bounded', () => {
  const close = expiry.deadlineCloseInstant('2026-10-20', null);
  assert.equal(expiry.isPastDeadline(close, new Date('2026-10-21T17:59:59Z'), 6), false);
  assert.equal(expiry.isPastDeadline(close, new Date('2026-10-21T18:00:00Z'), 6), true);
  assert.equal(expiry.isPastDeadline(close, new Date('2026-10-21T12:00:00Z'), 0), true);
  assert.equal(expiry.expiryGraceHours({}), expiry.DEFAULT_GRACE_HOURS);
  assert.equal(expiry.expiryGraceHours({ OPEN_CALL_EXPIRY_GRACE_HOURS: '12' }), 12);
  assert.equal(expiry.expiryGraceHours({ OPEN_CALL_EXPIRY_GRACE_HOURS: '0' }), 0);
  assert.equal(expiry.expiryGraceHours({ OPEN_CALL_EXPIRY_GRACE_HOURS: '-3' }), expiry.DEFAULT_GRACE_HOURS);
  assert.equal(expiry.expiryGraceHours({ OPEN_CALL_EXPIRY_GRACE_HOURS: 'soon' }), expiry.DEFAULT_GRACE_HOURS);
  assert.equal(expiry.expiryGraceHours({ OPEN_CALL_EXPIRY_GRACE_HOURS: '500' }), expiry.MAX_GRACE_HOURS);
});

test('the daily cycle runs the expiry pass before every discovery lane and the digest', () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/services/scheduler.ts'), 'utf8');
  const branch = source.slice(source.indexOf("scheduleType === 'daily-digest') {\n        // ---- Daily Digest Job"));
  const expiryAt = branch.indexOf('closeExpiredOpenCalls(pool)');
  assert.ok(expiryAt > 0, 'daily-digest branch calls closeExpiredOpenCalls');
  for (const lane of ['runScanExecution(pool', 'runForumScan(pool', 'runSourceFeeds(pool', 'runCohortBridge(pool', 'assembleAndSendDailyDigest(']) {
    const at = branch.indexOf(lane);
    assert.ok(at < 0 || at > expiryAt, `${lane} runs after the expiry pass`);
  }
});

if (!process.env.DATABASE_URL) {
  console.log('Skipping open-call expiry DB tests: DATABASE_URL not set');
} else {
  const { Pool } = require('pg');
  const schema = `call_expiry_${process.pid}_${Date.now()}`;
  process.env.PGOPTIONS = `-c search_path=${schema}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, options: '' });
  let db;
  let pool;
  // Oct 22 AoE ends Oct 23 12:00Z, so its 6h grace runs to 18:00Z.
  const NOW = new Date('2026-10-23T17:00:00Z');

  test.before(async () => {
    await admin.query(`CREATE SCHEMA ${schema}`);
    db = require('../src/db');
    pool = db.getPool();
    await pool.query('CREATE TABLE scan_entries (LIKE public.scan_entries INCLUDING ALL)');
    await pool.query('ALTER TABLE scan_entries ALTER COLUMN id DROP DEFAULT');
    await pool.query('ALTER TABLE scan_entries ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
    await db.ensureAppStateTable();
  });
  test.after(async () => {
    if (db) await db.closePool();
    await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await admin.end();
  });
  test.beforeEach(async () => {
    await pool.query('TRUNCATE scan_entries, app_state RESTART IDENTITY CASCADE');
  });

  async function row(name, { status = 'approved', classification = 'GRANT', lifecycle = 'open', deadline = null, deadlineParsed = null } = {}) {
    return (await pool.query(`INSERT INTO scan_entries
      (name, description, source_url, wire, prompt_variant, scan_source, scan_date, status, classification, lifecycle, deadline, deadline_parsed, metadata)
      VALUES ($1, 'Fixture', $2, 'crypto', 'A', 'manual-intake', CURRENT_DATE, $3, $4, $5, $6, $7, '{"keep":1}'::jsonb) RETURNING id`,
      [name, `https://example.org/${encodeURIComponent(name)}`, status, classification, lifecycle, deadline, deadlineParsed])).rows[0].id;
  }

  async function read(id) {
    return (await pool.query('SELECT status, classification, lifecycle, metadata FROM scan_entries WHERE id = $1', [id])).rows[0];
  }

  test('expired open calls are closed in place; everything else is left alone; a rerun closes nothing', async () => {
    const expired = await row('Flap Fixture Season 4', { deadline: 'October 20, 2026', deadlineParsed: '2026-10-20' });
    const legacy = await row('Legacy null lifecycle', { status: 'queued', lifecycle: null, deadline: '2026-10-21 11:59 PM PT', deadlineParsed: '2026-10-21' });
    const registry = await row('Evergreen registry row', { status: 'archived', deadline: '2026-10-01', deadlineParsed: '2026-10-01' });
    const inGrace = await row('Closes yesterday AoE', { deadline: 'Oct 22', deadlineParsed: '2026-10-22' });
    const future = await row('Future', { deadline: 'Nov 30', deadlineParsed: '2026-11-30' });
    const stated = await row('Closed earlier today', { deadline: 'Oct 23, 9:00 UTC', deadlineParsed: '2026-10-23' });
    const untouched = [
      await row('Forthcoming', { lifecycle: 'forthcoming', deadlineParsed: '2026-10-01' }),
      await row('Unknown lifecycle', { lifecycle: 'unknown', deadlineParsed: '2026-10-01' }),
      await row('News item', { classification: 'NEWS', deadlineParsed: '2026-10-01' }),
      await row('Declined', { status: 'declined', deadlineParsed: '2026-10-01' }),
      await row('Duplicate', { status: 'duplicate', deadlineParsed: '2026-10-01' }),
      await row('No parsed deadline', { deadline: 'Rolling' }),
    ];

    const preview = await expiry.closeExpiredOpenCalls(pool, { now: NOW, graceHours: 6, dryRun: true });
    assert.deepEqual(preview.closed.map(call => call.id).sort(), [expired, legacy, registry, stated].sort());
    assert.equal((await read(expired)).classification, 'GRANT', 'dry run writes nothing');
    assert.equal(await db.getAppState(expiry.OPEN_CALL_EXPIRY_STATE_KEY), null);

    const result = await expiry.closeExpiredOpenCalls(pool, { now: NOW, graceHours: 6 });
    assert.deepEqual(result.closed.map(call => call.id).sort(), [expired, legacy, registry, stated].sort());
    assert.equal(result.checked, 5, 'the far-future row is not even read');
    assert.equal(result.stillOpen, 1);

    const closed = await read(expired);
    assert.equal(closed.status, 'approved');
    assert.equal(closed.classification, 'EXPIRED');
    assert.equal(closed.lifecycle, 'closed');
    assert.equal(closed.metadata.keep, 1);
    assert.equal(closed.metadata.auto_closed.prior_classification, 'GRANT');
    assert.equal(closed.metadata.auto_closed.prior_lifecycle, 'open');
    assert.equal(closed.metadata.auto_closed.closes_at, '2026-10-21T12:00:00.000Z');
    assert.equal(closed.metadata.auto_closed.zone, 'AoE');
    assert.equal(closed.metadata.auto_closed.grace_hours, 6);
    assert.equal((await read(legacy)).metadata.auto_closed.prior_lifecycle, null);
    assert.equal((await read(legacy)).status, 'queued');
    assert.equal((await read(registry)).status, 'archived');

    for (const id of [inGrace, future]) {
      const open = await read(id);
      assert.equal(open.classification, 'GRANT');
      assert.equal(open.lifecycle, 'open');
      assert.equal(open.metadata.auto_closed, undefined);
    }
    for (const id of untouched) assert.equal((await read(id)).metadata.auto_closed, undefined);
    assert.equal(Number((await pool.query('SELECT count(*) FROM scan_entries')).rows[0].count), 12, 'nothing is deleted');

    const summary = await db.getAppState(expiry.OPEN_CALL_EXPIRY_STATE_KEY);
    assert.equal(summary.closed.length, 4);

    const rerun = await expiry.closeExpiredOpenCalls(pool, { now: NOW, graceHours: 6 });
    assert.equal(rerun.closed.length, 0);

    const later = await expiry.closeExpiredOpenCalls(pool, { now: new Date('2026-10-24T00:00:00Z'), graceHours: 6 });
    assert.deepEqual(later.closed.map(call => call.id), [inGrace]);
  });

  test('a row edited back out of GRANT between read and write is not closed', async (t) => {
    const id = await row('Raced', { deadlineParsed: '2026-10-01' });
    const original = pool.query.bind(pool);
    t.mock.method(pool, 'query', async (sql, params) => {
      if (/UPDATE scan_entries se/.test(sql)) await original(`UPDATE scan_entries SET classification = 'NEWS' WHERE id = $1`, [id]);
      return original(sql, params);
    });
    const result = await expiry.closeExpiredOpenCalls(pool, { now: NOW, graceHours: 6 });
    assert.equal(result.closed.length, 0);
    assert.equal((await read(id)).classification, 'NEWS');
  });
}
