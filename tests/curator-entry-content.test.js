test('unwithhold returns an approved entry without enqueueing or sending', async () => {
  const row = await entry('Held', {
    metadata: { keeper: true, withheld: { by: 'agent:earlier', reason: 'stale' } },
  });
  await queue(row.id, 'withheld');
  const before = await snap(row.id);

  const dry = await unwithhold(row.id, evidence({ dryRun: true }));
  assert.equal(dry.status, 200);
  const dryBody = await dry.json();
  assert.equal(dryBody.dryRun, true);
  assert.equal(dryBody.enqueued, false);
  assert.equal(dryBody.sent, false);
  assert.equal((await snap(row.id)).queue.status, 'withheld');

  const res = await unwithhold(row.id, evidence());
  assert.equal(res.status, 200, await res.clone().text());
  const body = await res.json();
  assert.equal(body.action, 'unwithhold');
  assert.equal(body.status, 'approved');
  assert.equal(body.enqueued, false);
  assert.equal(body.sent, false);
  assert.equal(body.actioned_by, 'agent:hedwig');

  const after = await snap(row.id);
  assert.equal(after.entry.status, 'approved');
  assert.equal(after.entry.distributable, before.entry.distributable);
  assert.equal(after.queue, null);
  assert.equal(after.logs, 0);
  assert.equal(after.entry.actioned_by, 'agent:hedwig');
  assert.equal(after.entry.action_reason, evidence().reason);
  assert.equal(after.entry.metadata.keeper, true);
  assert.equal(after.entry.metadata.withheld.reason, 'stale');
  assert.equal(after.entry.metadata.unwithhold.length, 1);
  assert.equal(after.entry.metadata.unwithhold[0].actor, 'agent:hedwig');
  assert.equal(after.entry.metadata.unwithhold[0].previous_actioned_by, 'agent:earlier');
  assert.equal(after.entry.metadata.curator_evidence.by, 'agent:hedwig');
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM publication_queue')).rows[0].n, 0);
});

