test('confirm, reason, and sources are required and a read-only key is forbidden', async () => {
  const row = await entry('Needs a fix');
  const before = await snap(row.id);

  const missingConfirm = await patchContent(row.id, {
    reason: 'Official page has the corrected text.',
    sources: ['https://example.org/program'],
    name: 'Corrected name',
  });
  assert.equal(missingConfirm.status, 400);
  assert.equal((await missingConfirm.json()).error, 'confirm_required');

  const missingReason = await patchContent(row.id, {
    confirm: true,
    sources: ['https://example.org/program'],
    name: 'Corrected name',
  });
  assert.equal(missingReason.status, 400);
  assert.match((await missingReason.json()).error, /reason/);

  const missingSources = await patchContent(row.id, {
    confirm: true,
    reason: 'Official page has the corrected text.',
    name: 'Corrected name',
  });
  assert.equal(missingSources.status, 400);
  assert.match((await missingSources.json()).error, /sources/);

  const reader = await patchContent(row.id, evidence({ name: 'Corrected name' }), { key: READ });
  assert.equal(reader.status, 403);

  const internal = await unwithhold(row.id, {
    reason: 'Release it.',
    sources: ['https://example.org/program'],
  }, { key: INTERNAL, idempotency: null });
  assert.equal(internal.status, 400);
  assert.equal((await internal.json()).error, 'confirm_required');

  assert.equal((await snap(row.id)).entry.name, before.entry.name);
  assert.equal((await snap(row.id)).entry.actioned_by, 'agent:earlier');
  assert.equal((await snap(row.id)).logs, 0);
});

