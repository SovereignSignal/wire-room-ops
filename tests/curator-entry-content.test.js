function request(method, urlPath, body, { key = TOKEN, idempotency = idem() } = {}) {
  return fetch(`${base}${urlPath}`, {
    method,
    headers: {
      'Content-Type': 'application/json',
      ...(key ? { Authorization: `Bearer ${key}` } : {}),
      ...(idempotency ? { 'Idempotency-Key': idempotency } : {}),
    },
    body: JSON.stringify(body ?? {}),
  });
}

function patchContent(id, body, opts) {
  return request('PATCH', `/api/scan/entries/${id}/content`, body, opts);
}

function unwithhold(id, body, opts) {
  return request('POST', `/api/scan/entries/${id}/unwithhold`, body, opts);
}

async function entry(name, opts = {}) {
  const row = (await pool.query(
    `INSERT INTO scan_entries
      (name, description, source_url, wire, wires, prompt_variant, scan_source, scan_date, status, classification, distributable, quality_score, enriched_summary, actioned_by, metadata)
     VALUES ($1, $2, $3, 'crypto', ARRAY['crypto'], 'A', 'manual-intake', CURRENT_DATE, $4, 'GRANT', $5, 80, $6, $7, $8::jsonb)
     RETURNING *`,
    [
      name,
      opts.description || 'Fixture grant description long enough to approve.',
      opts.sourceUrl || `https://example.org/${encodeURIComponent(name)}`,
      opts.status || 'approved',
      opts.distributable !== false,
      opts.summary || 'Example Foundation funds independent teams working in the open.',
      opts.actor || 'agent:earlier',
      JSON.stringify(opts.metadata || { keeper: true, summary: 'Old card summary.' }),
    ],
  )).rows[0];
  if (opts.decisionAt !== false && (opts.status || 'approved') === 'approved') {
    await pool.query('UPDATE scan_entries SET decision_at = NOW() - INTERVAL \'1 day\' WHERE id = $1', [row.id]);
  }
  return row;
}

async function queue(id, status) {
  await pool.query(
    `INSERT INTO publication_queue (entry_id, status, available_at, error_message)
     VALUES ($1, $2, NOW() + INTERVAL '1 hour', $3)`,
    [id, status, status === 'withheld' ? 'Withheld by test' : null],
  );
}

async function snap(id) {
  const row = (await pool.query(
    `SELECT id, status, distributable, actioned_by, action_reason, name, description, enriched_summary,
            amount, amount_numeric, amount_currency, deadline, deadline_parsed::text AS deadline_parsed,
            source_url, classification, tags, auto_summarize_failed, decision_at, metadata
     FROM scan_entries WHERE id = $1`,
    [id],
  )).rows[0];
  const queued = (await pool.query(
    'SELECT status, error_message FROM publication_queue WHERE entry_id = $1',
    [id],
  )).rows[0] || null;
  const logs = (await pool.query(
    'SELECT count(*)::int AS n FROM distribution_logs WHERE entry_id = $1',
    [id],
  )).rows[0].n;
  return { entry: row, queue: queued, logs };
}

