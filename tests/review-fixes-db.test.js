test('approval and queue insertion commit together; quiet approvals create no publication job', async (t) => {
  const actions = require('../src/services/entry-actions');
  t.mock.method(queue, 'drainPublicationQueue', async () => {});
  t.mock.method(db, 'insertApprovedSummary', async () => null);
  const a = await entry('Atomic'); const q = await entry('QuietApproval'); const blocked = await entry('Blocked');
  await pool.query("UPDATE scan_entries SET status = 'queued', org_id = 1, enriched_summary = repeat('summary ',20)");
  await actions.singleEntryAction(a.id, 'approve', { actor: 'user:test' });
  await actions.singleEntryAction(q.id, 'approve', { quiet: true, actor: 'user:test' });
  assert.deepEqual((await pool.query('SELECT entry_id FROM publication_queue')).rows.map(r => r.entry_id), [a.id]);
  await pool.query(`CREATE FUNCTION reject_queue_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'queue write rejected'; END $$`);
  await pool.query('CREATE TRIGGER reject_queue BEFORE INSERT ON publication_queue FOR EACH ROW EXECUTE FUNCTION reject_queue_insert()');
  try {
    await assert.rejects(actions.singleEntryAction(blocked.id, 'approve'), /queue write rejected/);
    assert.equal((await pool.query('SELECT status FROM scan_entries WHERE id=$1', [blocked.id])).rows[0].status, 'queued');
  } finally {
    await pool.query('DROP TRIGGER reject_queue ON publication_queue');
    await pool.query('DROP FUNCTION reject_queue_insert()');
    await new Promise(resolve => setImmediate(resolve));
  }
});

test('each paid attempt checks the preceding settled usage and blocks concurrent spend', async () => {
  const { withDiscoveryBudget } = require('../src/services/budget-guard');
  let calls = 0, release;
  const held = withDiscoveryBudget(pool, async () => {
    calls++;
    await new Promise(resolve => { release = resolve; });
    await pool.query(`INSERT INTO api_usage_log (provider,model,purpose,estimated_cost_usd,duration_ms)
      VALUES ('parallel','search','scan',1000,0)`);
  });
  while (!release) await new Promise(resolve => setImmediate(resolve));
  try { await assert.rejects(withDiscoveryBudget(pool, async () => { calls++; }), /budget busy/); }
  finally { release(); await held; }
  await assert.rejects(withDiscoveryBudget(pool, async () => { calls++; }), /budget unavailable/);
  assert.equal(calls, 1);
});

