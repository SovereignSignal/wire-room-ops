const verified = item => ({ is_open: true, apply_url: item.url, citationUrl: item.url, confidence: 'high' });

test('weekly cap shares coverage across wires and retains overflow beyond the date checkpoint', async (t) => {
  await weeklyFixtures(t, 41);
  const checked = [];
  t.mock.method(parallel, 'verifyOpportunities', async items => { checked.push(...items); return items.map(verified); });
  const issue = await weekly.runWeeklyIssue(pool);
  assert.equal(checked.length, 40); assert.match(issue.markdown, /# \*\*OSS\*\*/);
  const prior = await db.getAppState('weekly:last-issue'); assert.equal(prior.deferredEntryIds.length, 1);
  await pool.query("UPDATE distribution_logs SET created_at = NOW() - INTERVAL '30 days'");
  checked.length = 0;
  await weekly.runWeeklyIssue(pool);
  assert.equal(checked.length, 1, 'overflow must be gathered despite an older publication date');
});

