test('overdue rows respace after one send, and a finished send is not repeated', async () => {
  await channel('crypto', 'crypto-chat');
  await enablePace();
  const ids = [];
  for (let i = 0; i < 5; i++) {
    const row = await entry(`Old ${i}`);
    ids.push(row.id);
    await pool.query(`UPDATE scan_entries SET status = 'approved' WHERE id = $1`, [row.id]);
    await pool.query(`INSERT INTO publication_queue (entry_id, available_at) VALUES ($1, NOW() - ($2 || ' minutes')::interval)`, [row.id, String(50 - i)]);
  }
  await queue.drainPublicationQueue();
  assert.equal(sends, 1);
  const rest = (await pool.query(`SELECT entry_id, available_at FROM publication_queue WHERE status = 'queued' ORDER BY available_at, entry_id`)).rows;
  assert.equal(rest.length, 4);
  assert.ok(Math.abs(minutesApart(rest[0].available_at, new Date()) - 20) < 1);
  for (let i = 1; i < rest.length; i++) {
    assert.ok(Math.abs(minutesApart(rest[i].available_at, rest[i - 1].available_at) - 20) < 0.1);
  }
  const sentId = ids.find(id => !rest.some(row => row.entry_id === id));
  await pool.query(`UPDATE publication_queue SET status = 'running', lease_expires_at = NOW() - INTERVAL '1 hour' WHERE entry_id = $1`, [sentId]);
  await queue.drainPublicationQueue();
  assert.equal(sends, 1);
  assert.equal((await pool.query(`SELECT status FROM publication_queue WHERE entry_id = $1`, [sentId])).rows[0].status, 'done');
  const outgoing = await listOutgoing();
  assert.equal(outgoing.counts.waiting, 4);
  assert.equal(outgoing.sent.length, 1);
  assert.match(outgoing.banner, /4 scheduled/);
});

