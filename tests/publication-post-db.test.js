// Frozen Telegram text: written when a row is queued, sent as stored, regenerated on edit.
process.env.DEV_MODE = 'true';
require('ts-node/register/transpile-only');
const test = require('node:test');
const assert = require('node:assert/strict');
const { Pool } = require('pg');
if (!process.env.DATABASE_URL) { console.log('Skipping publication post tests: DATABASE_URL not set'); process.exit(0); }

const schema = `post_text_${process.pid}_${Date.now()}`;
process.env.PGOPTIONS = `-c search_path=${schema}`;
const admin = new Pool({ connectionString: process.env.DATABASE_URL, options: '' });
const db = require('../src/db');
const pool = db.getPool();
let sends = 0;
let generated = 0;
let nextTelegram = 'frozen-draft';

test.before(async () => {
  await admin.query(`CREATE SCHEMA ${schema}`);
  await pool.query('CREATE TABLE scan_entries (LIKE public.scan_entries INCLUDING ALL)');
  await pool.query('ALTER TABLE scan_entries ALTER COLUMN id DROP DEFAULT');
  await pool.query('ALTER TABLE scan_entries ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
  await db.ensureDistributionTables();
  await db.ensureAppStateTable();
});

test.beforeEach(async (t) => {
  sends = 0;
  generated = 0;
  nextTelegram = 'frozen-draft';
  await pool.query('TRUNCATE scan_entries, distribution_channels, distribution_config, distribution_logs, publication_queue, app_state RESTART IDENTITY CASCADE');
  t.mock.method(require('../src/services/post-generator'), 'generatePosts', async () => {
    generated += 1;
    return { tweet: 'tweet-draft', telegram: nextTelegram, model: 'mock-model', checkResult: { ok: true, violations: [], source: 'model', attempts: 1, rejected: [] }, verifierResult: { ok: true, model: 'mock-verify', unsupported: [], error: null } };
  });
  t.mock.method(require('../src/services/telegram-channel'), 'sendChannelMessage', async (_token, _chat, text) => {
    sends += 1;
    return { messageId: sends, text };
  });
});

test.after(async () => {
  await db.closePool();
  await admin.query(`DROP SCHEMA ${schema} CASCADE`);
  await admin.end();
});

async function entry(name) {
  return (await pool.query(`INSERT INTO scan_entries
    (name, description, source_url, wire, wires, prompt_variant, scan_source, scan_date, status, classification, distributable, quality_score, org_id, enriched_summary, amount)
    VALUES ($1, 'Fixture grant description long enough', $2, 'crypto', ARRAY['crypto'], 'A', 'manual-intake', CURRENT_DATE, 'queued', 'GRANT', true, 80, NULL, $3, '$50K') RETURNING *`,
    [name, `https://example.invalid/${encodeURIComponent(name)}`, 'summary '.repeat(20)])).rows[0];
}

async function channel() {
  await pool.query(`INSERT INTO distribution_channels (wire, channel, name, enabled, target_id, credentials)
    VALUES ('crypto', 'telegram', 'crypto', true, 'crypto-chat', '{"bot_token":"fixture"}')`);
}

test('approving freezes the draft, and send uses that text without generating again', async (t) => {
  await channel();
  const row = await entry('Freeze me');
  const actions = require('../src/services/entry-actions');
  t.mock.method(require('../src/services/publication-queue'), 'drainPublicationQueue', async () => {});
  t.mock.method(db, 'insertApprovedSummary', async () => null);
  await actions.singleEntryAction(row.id, 'approve', { actor: 'user:test' });
  const stored = (await pool.query('SELECT post_text, model FROM publication_queue WHERE entry_id = $1', [row.id])).rows[0];
  assert.equal(stored.post_text, 'frozen-draft');
  assert.equal(stored.model, 'mock-model');
  assert.equal(generated, 1);

  generated = 0;
  nextTelegram = 'should-not-send';
  const { distributeEntry } = require('../src/services/distribution');
  await distributeEntry(row.id, 'crypto');
  assert.equal(generated, 0);
  assert.equal(sends, 1);
  const log = (await pool.query(`SELECT post_text FROM distribution_logs WHERE entry_id = $1 AND status = 'success'`, [row.id])).rows[0];
  assert.equal(log.post_text, 'frozen-draft');
});

test('a legacy row with no stored text is generated at send time', async () => {
  await channel();
  const row = await entry('Legacy');
  await pool.query(`UPDATE scan_entries SET status = 'approved' WHERE id = $1`, [row.id]);
  await pool.query('INSERT INTO publication_queue (entry_id, available_at) VALUES ($1, NOW())', [row.id]);
  nextTelegram = 'generated-at-send';
  const { distributeEntry } = require('../src/services/distribution');
  await distributeEntry(row.id, 'crypto');
  assert.equal(generated, 1);
  assert.equal(sends, 1);
  const log = (await pool.query(`SELECT post_text FROM distribution_logs WHERE entry_id = $1`, [row.id])).rows[0];
  assert.equal(log.post_text, 'generated-at-send');
});

test('editing queued post inputs regenerates the stored text and does not send', async () => {
  const row = await entry('Edit me');
  await pool.query(`UPDATE scan_entries SET status = 'approved' WHERE id = $1`, [row.id]);
  await pool.query(`INSERT INTO publication_queue (entry_id, status, post_text) VALUES ($1, 'queued', 'old-draft')`, [row.id]);
  nextTelegram = 'regenerated-draft';
  const { updateEntryContent } = require('../src/services/entry-content');
  const result = await updateEntryContent(row.id, {
    description: 'A longer corrected description for the queued publication.',
  }, {
    actor: 'user:test',
    reason: 'The funder page was corrected.',
    sources: ['https://example.org/program'],
  });
  assert.equal(result.sent, false);
  assert.equal(result.enqueued, false);
  assert.equal(generated, 1);
  assert.equal(sends, 0);
  const stored = (await pool.query('SELECT post_text, status FROM publication_queue WHERE entry_id = $1', [row.id])).rows[0];
  assert.equal(stored.status, 'queued');
  assert.equal(stored.post_text, 'regenerated-draft');
});
